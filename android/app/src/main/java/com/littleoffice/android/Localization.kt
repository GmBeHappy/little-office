private val LocalOfficeLanguage =
    staticCompositionLocalOf<MutableState<String>> { error("Language provider required") }

@Composable
fun ProvideOfficeLanguage(content: @Composable () -> Unit) {
    val context = LocalContext.current
    val language = remember {
        mutableStateOf(
            context
                .getSharedPreferences("office-language", Context.MODE_PRIVATE)
                .getString(
                    "language",
                    if (java.util.Locale.getDefault().language == "th") "th" else "en",
                ) ?: "en"
        )
    }
    CompositionLocalProvider(LocalOfficeLanguage provides language, content = content)
}

@Composable
fun LanguagePicker() {
    val context = LocalContext.current
    val language = LocalOfficeLanguage.current
    Row {
        listOf("en" to "English", "th" to "ไทย").forEach { (value, label) ->
            FilterChip(
                language.value == value,
                {
                    language.value = value
                    context
                        .getSharedPreferences("office-language", Context.MODE_PRIVATE)
                        .edit()
                        .putString("language", value)
                        .apply()
                },
                label = { Text(label) },
            )
        }
    }
}

@Composable
fun officeTranslation(text: String): String =
    if (LocalOfficeLanguage.current.value == "th") thai[text] ?: text else text

@Composable
fun officeLocale(): java.util.Locale =
    java.util.Locale.forLanguageTag(LocalOfficeLanguage.current.value)

@Composable
fun OfficeText(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = Color.Unspecified,
    fontWeight: FontWeight? = null,
    style: TextStyle = LocalTextStyle.current,
) {
    Text(
        if (LocalOfficeLanguage.current.value == "th") thai[text] ?: text else text,
        modifier,
        color = color,
        fontWeight = fontWeight,
        style = style,
    )
}

